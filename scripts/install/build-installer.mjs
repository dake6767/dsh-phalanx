import { readFile, writeFile, chmod } from 'node:fs/promises'
import { pathToFileURL } from 'node:url'

// One source owner per language; the committed standalone entry is generated data.
const directory = new URL('./', import.meta.url)
const [bootstrap, installer] = await Promise.all([
  readFile(new URL('bootstrap.sh', directory), 'utf8'),
  readFile(new URL('installer.py', directory), 'utf8'),
])
const target = new URL('../../install.sh', directory)
const generated = bootstrap.replace('#!/bin/bash\n', '#!/bin/bash\n# Generated by scripts/install/build-installer.mjs; edit its sources.\n') + installer + '\nDSH_PHALANX_INSTALLER_PYTHON\n'
export async function checkInstaller() {
  if (await readFile(target, 'utf8') !== generated) throw new Error('install.sh is stale; run node scripts/install/build-installer.mjs')
}
if (process.argv[1] !== undefined && pathToFileURL(process.argv[1]).href === import.meta.url) {
  if (process.argv.includes('--check')) await checkInstaller()
  else { await writeFile(target, generated); await chmod(target, 0o755) }
}
